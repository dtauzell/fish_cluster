import { test, expect } from '@playwright/test';
import { analyzeVideo, analysisJSON } from './helpers.mjs';
test.use({ serviceWorkers:'block' });
test('intervening frame mode decodes extra observations but retains the review sample schedule', async ({page})=>{
 await analyzeVideo(page);
 await page.locator('#nav-setup').click();
 await page.locator('#interval').fill('400');
 await page.locator('#interval').press('Tab');
 await page.locator('#analyze').click();
 await expect(page).toHaveURL(/#results$/);
 const baseline=await analysisJSON(page);
 expect(baseline.settings.interveningFrames).toBe(false);
 await page.locator('#nav-setup').click();
 await page.locator('#intervening-frames').check();
 await page.locator('#analyze').click();
 await expect(page).toHaveURL(/#results$/,{timeout:45000});
 const dense=await analysisJSON(page);
 expect(dense.analysisComplete).toBe(true);
 expect(dense.settings.interveningFrames).toBe(true);
 expect(dense.frames.map(f=>f.timestampMs)).toEqual(baseline.frames.map(f=>f.timestampMs));
 expect(dense.frames.at(-1).processedVideoFrames).toBeGreaterThan(dense.frames.length);
 expect(dense.frames.every(f=>Number.isFinite(f.sourceTimestampMs))).toBe(true);
 await expect(page.locator('#human-done')).toBeEnabled();
 await page.locator('#nav-setup').click();
 await page.locator('#analyze').click();
 await expect(page.locator('#status')).toContainText('Processing intervening frames');
 await page.locator('#cancel').click();
 await expect(page).toHaveURL(/#results$/);
 expect((await analysisJSON(page)).analysisComplete).toBe(false);
 await expect(page.locator('#human-done')).toBeEnabled();
});
