import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { gitVersion } from './git-version.mjs';

const root = new URL('../dist/', import.meta.url);
async function filesIn(directory, prefix = '') {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.map(entry => entry.isDirectory()
    ? filesIn(new URL(`${entry.name}/`, directory), `${prefix}${entry.name}/`)
    : `${prefix}${entry.name}`));
  return files.flat().sort();
}

export async function offlineManifest({ version = gitVersion() } = {}) {
  const files = (await filesIn(root)).filter(file => file !== 'offline-assets.js' && !file.startsWith('_'));
  const hash = createHash('sha256');
  for (const file of files) {
    hash.update(file).update('\0').update(await readFile(new URL(file, root))).update('\0');
  }
  hash.update(JSON.stringify(version));
  // Optional test recordings download on demand instead of delaying app installation.
  const assets = files.filter(file => file !== 'sw.js' && !file.startsWith('test-video-clips/')).map(file => `./${file}`);
  return `// Generated by npm run offline:prepare. Do not edit.\nself.FISH_CLUSTER_OFFLINE = ${JSON.stringify({ revision: hash.digest('hex'), version, assets }, null, 2)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(new URL('offline-assets.js', root), await offlineManifest());
  console.log('Offline asset list and revision updated.');
}
